#!/usr/bin/env python3
"""Generate the static Ansible inventory from the deployment inputs (docs/07, docs/12).

Groups: management, primary, lb, testing, plus `fixed` (their parent; group_vars/fixed.yml holds the fixed-host role settings). The cloud_app group is not written here: inventory/cloud_app.py reads it from ops.instances.
No secret is read or written: ssh_key_reference is a key PATH, and every other credential stays an env:// reference.

  gen-inventory.py --inputs deploy/inputs/deployment-inputs.local.json [--bootstrap] [--ssh-key PATH] [--local-role ROLE] [--output inventory/generated.yml]

--bootstrap connects as hosts.*.ssh_user (the bootstrap user, root) for the first run; without it the fixed hosts' deploy user is used. That is
root, an approved deviation (docs/07): the fixed hosts have no separate deploy user. Cloud VMs still use `drproj` (group_vars/cloud_app.yml).
--ssh-key replaces every host's key path (for a controller whose own key differs from the workstation's, e.g. the management VM).
--local-role marks that host `ansible_connection: local` (the controller reaching itself).
Exit 2 on a missing/invalid input (never a partial inventory).
"""
import argparse
import ipaddress
import json
import os
import sys

GROUPS = {"management": "management", "primary": "primary", "load_balancer": "lb", "testing": "testing"}
DEPLOY_USER = "root"


class InputError(Exception):
    pass


def host_entry(name, host, bootstrap, ssh_key=None, local=False):
    ip = host.get("public_ip")
    if not ip:
        raise InputError(f"hosts.{name}.public_ip is missing")
    try:
        ipaddress.ip_address(ip)
    except ValueError as exc:
        raise InputError(f"hosts.{name}.public_ip is not an IP address") from exc
    key = host.get("ssh_key_reference")
    if not key:
        raise InputError(f"hosts.{name}.ssh_key_reference is missing")
    if "://" in key:
        raise InputError(f"hosts.{name}.ssh_key_reference must be a key file path, not a reference URL")
    user = host.get("ssh_user")
    if bootstrap and not user:
        raise InputError(f"hosts.{name}.ssh_user is missing")
    entry = {
        "ansible_host": ip,
        "ansible_user": user if bootstrap else DEPLOY_USER,
        "ansible_ssh_private_key_file": os.path.expanduser(ssh_key or key),
        "drproj_role": name,
    }
    if local:
        entry["ansible_connection"] = "local"
    return entry


def build(inputs, bootstrap=False, ssh_key=None, local_role=None):
    hosts = inputs.get("hosts")
    if not isinstance(hosts, dict):
        raise InputError("hosts is missing")
    children = {}
    for name, group in GROUPS.items():
        if name not in hosts:
            raise InputError(f"hosts.{name} is missing")
        # host names differ from group names (Ansible warns and resolves ambiguously otherwise)
        children[group] = {"hosts": {f"{name}-vm": host_entry(name, hosts[name], bootstrap, ssh_key, name == local_role)}}
    if local_role is not None and local_role not in hosts:
        raise InputError(f"--local-role {local_role} is not one of hosts.*")
    children["fixed"] = {"children": {group: {} for group in GROUPS.values()}}
    children["cloud_app"] = {"hosts": {}}
    return {"all": {"children": children}}


def dump_yaml(inv):
    """Tiny YAML writer for the fixed inventory shape (no PyYAML dependency)."""
    lines = ["---", "# Generated by scripts/gen-inventory.py from the deployment inputs. Do not edit; do not commit.", "all:", "  children:"]
    for group, body in inv["all"]["children"].items():
        lines.append(f"    {group}:")
        if "children" in body:
            lines.append("      children:")
            lines += [f"        {child}: {{}}" for child in body["children"]]
            continue
        if not body["hosts"]:
            lines.append("      hosts: {}")
            continue
        lines.append("      hosts:")
        for host, vars_ in body["hosts"].items():
            lines.append(f"        {host}:")
            for k, v in vars_.items():
                lines.append(f"          {k}: {json.dumps(v)}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--inputs", required=True)
    ap.add_argument("--output", default="-")
    ap.add_argument("--bootstrap", action="store_true")
    ap.add_argument("--ssh-key")
    ap.add_argument("--local-role", choices=sorted(GROUPS))
    args = ap.parse_args(argv)
    try:
        with open(args.inputs) as f:
            inputs = json.load(f)
        text = dump_yaml(build(inputs, args.bootstrap, args.ssh_key, args.local_role))
    except (OSError, ValueError, InputError) as exc:
        print(f"gen-inventory: {exc}", file=sys.stderr)
        return 2
    if args.output == "-":
        sys.stdout.write(text)
    else:
        with open(args.output, "w") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
